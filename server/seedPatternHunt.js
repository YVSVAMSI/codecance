let isSeeding = false;

export async function ensurePatternHuntSeed(prisma) {
  const count = await prisma.patternHuntProblem.count();
  const sample = await prisma.patternHuntProblem.findFirst({ where: { title: "Design Twitter (News Feed & Follow)", topicName: "Heap / Priority Queue" } });
  if ((count !== PATTERN_HUNT_PROBLEMS.length || !sample) && !isSeeding) {
    isSeeding = true;
    try {
      await prisma.patternHuntProblem.deleteMany({});
      let order = 0;
      for (const prob of PATTERN_HUNT_PROBLEMS) {
        await prisma.patternHuntProblem.create({
          data: {
            title: prob.title,
            difficulty: prob.difficulty,
            topicName: prob.topicName,
            patternName: prob.patternName,
            problemLink: prob.problemLink,
            order: order++
          }
        });
      }
    } finally {
      isSeeding = false;
    }
  }
}

import { evaluateSemanticAnswer } from './semanticEvaluator.js';

export function normalizePatternString(str) {
  if (!str) return "";
  return str.toLowerCase().replace(/[^a-z0-9]/g, '');
}

export function evaluatePatternRecognition(userGuess, expectedPatternName, expectedTopicName = "") {
  const evalResult = evaluateSemanticAnswer(userGuess, expectedPatternName, expectedTopicName);
  return evalResult.validApproach;
}
